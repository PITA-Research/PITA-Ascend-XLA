#ifndef METADEF_CXX_INC_EXE_GRAPH_RUNTIME_TILING_PARSE_CONTEXT_H_
#define METADEF_CXX_INC_EXE_GRAPH_RUNTIME_TILING_PARSE_CONTEXT_H_
#include "exe_graph/runtime/extended_kernel_context.h"
#include "graph/types.h"

namespace fe {
class PlatFormInfos;
}  // namespace fe

namespace gert {
class TilingParseContext : public ExtendedKernelContext {
 public:
  /**
   * Get the JSON string generated by operator compilation
   * @return JSON string
   */
  const ge::char_t *GetCompiledJson() const {
    return GetInputValue<const char *>(0);
  }
  /**
   * Get `CompiledInfo` instance
   * @tparam T instance type, this type needs to be consistent with the type of TilingParse when registering `IMPL_OP`
   * @return pointer to `CompiledInfo` instance
   */
  template <typename T>
  auto GetCompiledInfo() -> T * {
    auto av = GetOutput(0);
    if (av == nullptr) {
      return nullptr;
    }
    return av->GetValue<T *>();
  }
  /**
   * Get fe::PlatFormInfos pointer
   * @return fe::PlatFormInfos pointer
   */
  fe::PlatFormInfos *GetPlatformInfo() const {
    return GetInputValue<fe::PlatFormInfos *>(1);
  }
};
static_assert(std::is_standard_layout<TilingParseContext>::value,
              "The class TilingParseContext must be a POD");
}  // namespace gert
#endif  // METADEF_CXX_INC_EXE_GRAPH_RUNTIME_TILING_PARSE_CONTEXT_H_
